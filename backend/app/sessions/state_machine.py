from enum import Enum


class S(str, Enum):
    CREATED = "CREATED"
    PREPARING = "PREPARING"
    IN_PROGRESS = "IN_PROGRESS"
    AWAITING_EVIDENCE = "AWAITING_EVIDENCE"
    VALIDATING = "VALIDATING"
    VERIFIED = "VERIFIED"
    COMPLETED = "COMPLETED"
    NEEDS_CORRECTION = "NEEDS_CORRECTION"
    BLOCKED_BY_SAFETY = "BLOCKED_BY_SAFETY"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"
    ABANDONED = "ABANDONED"


TERMINAL = {S.COMPLETED, S.ABANDONED}
ACCEPTS_EVIDENCE = {S.IN_PROGRESS, S.AWAITING_EVIDENCE, S.NEEDS_CORRECTION, S.BLOCKED_BY_SAFETY}

ALLOWED: dict[S, set[S]] = {
    S.CREATED: {S.PREPARING, S.ABANDONED},
    S.PREPARING: {S.IN_PROGRESS, S.ABANDONED},
    S.IN_PROGRESS: {S.VALIDATING, S.NEEDS_HUMAN_REVIEW, S.ABANDONED},
    S.AWAITING_EVIDENCE: {S.VALIDATING, S.NEEDS_HUMAN_REVIEW, S.ABANDONED},
    S.NEEDS_CORRECTION: {S.VALIDATING, S.NEEDS_HUMAN_REVIEW, S.ABANDONED},
    S.BLOCKED_BY_SAFETY: {S.VALIDATING, S.NEEDS_HUMAN_REVIEW, S.ABANDONED},
    S.VALIDATING: {S.VERIFIED, S.AWAITING_EVIDENCE, S.NEEDS_CORRECTION, S.BLOCKED_BY_SAFETY, S.IN_PROGRESS},
    S.VERIFIED: {S.IN_PROGRESS, S.COMPLETED},
    S.NEEDS_HUMAN_REVIEW: {S.IN_PROGRESS, S.VERIFIED, S.BLOCKED_BY_SAFETY, S.ABANDONED},
    S.COMPLETED: set(),
    S.ABANDONED: set(),
}


class InvalidTransition(Exception):
    def __init__(self, src: str, dst: str):
        super().__init__(f"transition {src} → {dst} is not allowed")
        self.src, self.dst = src, dst


def check(src: str, dst: str) -> None:
    if S(dst) not in ALLOWED[S(src)]:
        raise InvalidTransition(src, dst)
